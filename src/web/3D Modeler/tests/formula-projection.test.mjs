import { evaluate, isFormula } from '../js/expr.js';
import * as M from '../js/sketch/model.js';
import { addProjected, projectCurve } from '../js/sketch/project.js';
import { createSolver } from '../js/sketch/solver.js';
let failed = 0;
const a = (c, m, x) => { if (!c) { failed++; console.log('FAIL', m, x === undefined ? '' : JSON.stringify(x)); } };
const near = (x, y) => Math.abs(x - y) < 1e-6;
a(evaluate('35/2') === 17.5, '35/2'); a(evaluate(' (40 - 2*3)/4 ') === 8.5, 'brackets'); a(evaluate('2^3') === 8, 'power'); a(near(evaluate('sqrt(2)*10'), 14.142135623), 'sqrt');
a(near(evaluate('pi*2'), Math.PI * 2), 'pi'); a(evaluate('12.5mm') === 12.5, 'unit'); a(evaluate('-3+10') === 7, 'unary'); a(near(evaluate('sin(30)*10'), 5), 'sin in degrees'); a(evaluate('.5*4') === 2, 'leading dot');
for (const bad of ['', '1/', 'abc', '2*(3', '1/0', 'alert(1)', '3 4', '1e5x']) a(isNaN(evaluate(bad)), 'rejects ' + bad, evaluate(bad));
a(!isFormula('17.5') && isFormula('35/2') && !isFormula(''), 'isFormula');
// projection onto the top face of the sample (z = 12, seen from +Z) and from below
const top = { o: [0, 0, 12], x: [1, 0, 0], y: [0, 1, 0], n: [0, 0, 1] };
const arc = { type: 'circle', c: [72, 8, 12], r: 8, n: [0, 0, 1], a: [72, 0, 12], b: [80, 8, 12], closed: false };
const p = projectCurve(top, arc);
a(p.type === 'arc' && near(p.a[0], 72) && near(p.a[1], 0) && near(p.b[0], 80), 'arc keeps its sense seen from its own side', p);
const below = { o: [0, 0, 0], x: [1, 0, 0], y: [0, -1, 0], n: [0, 0, -1] };
const q = projectCurve(below, arc);
a(q.type === 'arc' && near(q.a[0], 80) && near(q.a[1], -8), 'arc ends swap seen from the other side', q);
a(projectCurve(top, { type: 'circle', c: [0, 0, 0], r: 5, n: [1, 0, 0], a: [0, 5, 0], b: [0, 5, 0], closed: true }) === null, 'edge-on circle skipped');
a(projectCurve(top, { type: 'line', a: [1, 1, 0], b: [1, 1, 30] }) === null, 'line seen end-on skipped');
const sk = { geometry: [], constraints: [] };
a(addProjected(sk, top, { type: 'circle', c: [20, 25, 12], r: 6, n: [0, 0, -1], a: [26, 25, 12], b: [26, 25, 12], closed: true }), 'project hole');
a(addProjected(sk, top, { type: 'line', a: [8, 0, 12], b: [72, 0, 12] }) && addProjected(sk, top, arc), 'project line and arc');
a(!addProjected(sk, top, { type: 'line', a: [72, 0, 0], b: [8, 0, 0] }), 'same edge twice is refused');
a(sk.geometry.filter(g => g.type === 'point').length === 5, 'line and arc share the corner point', sk.geometry.filter(g => g.type === 'point').length);
// a rectangle made tangent to the projected hole: the hole must not move
const pts = [[30, 30], [50, 30], [50, 40], [30, 40]].map(c => M.addPoint(sk, c[0], c[1]));
const ls = [0, 1, 2, 3].map(i => M.addLine(sk, pts[i], pts[(i + 1) % 4]));
['horizontal', 'vertical', 'horizontal', 'vertical'].forEach((t, i) => M.addConstraint(sk, { type: t, line: ls[i] }));
const hole = sk.geometry.find(g => g.type === 'circle');
M.addConstraint(sk, { type: 'tangent', a: ls[3], b: hole.id });
const solver = await createSolver();
const r = solver.solve(sk);
const hc = M.curve(sk, hole.id);
a(r.ok && near(hc.c[0], 20) && near(hc.c[1], 25) && near(hc.r, 6), 'projected hole stays put', hc);
a(near(Math.abs(M.point(sk, pts[0])[0] - 20), 6), 'rectangle edge is tangent to the hole', M.point(sk, pts[0]));
const r2 = solver.solve(sk, [{ p: hole.c, x: 99, y: 99 }]);
a(near(M.curve(sk, hole.id).c[0], 20), 'dragging a projected point does nothing', r2);
console.log(failed ? failed + ' FAILED' : 'all formula and projection tests passed');
process.exitCode = failed ? 1 : 0;
